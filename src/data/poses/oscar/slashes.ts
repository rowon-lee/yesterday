/** 주된 베기의 기울기 (도, 화면 좌표: 0 = 앞, 양수 = 아래로). 상자 크기 w·h로 비율을 px로 */
export function slashAngle(id: string, w: number, h: number): number {
  const l = OSCAR_SLASHES[id]?.[0];
  if (!l) return 0;
  return Math.round((Math.atan2((l[3] - l[1]) * h, (l[2] - l[0]) * w) * 180) / Math.PI);
}
